  CREATE OR REPLACE EDITIONABLE TRIGGER "TRG_FD_UNIDADE_NUM_SEQ" 
BEFORE INSERT ON FD_UNIDADE_POLICIAL 
FOR EACH ROW 
 WHEN (NEW.NUM_SEQUENCIAL IS NULL) DECLARE 
 
    V_SEQ_PAI FD_UNIDADE_POLICIAL.NUM_SEQUENCIAL%TYPE; 
    V_PROXIMO NUMBER; 
 
BEGIN 
 
    /* ========================================================= 
       UNIDADE RAIZ 
       Exemplo: 
       001 
       002 
       003 
       ========================================================= */ 
 
    IF :NEW.ID_UNIDADE_PAI IS NULL THEN 
 
        SELECT NVL( 
                   MAX( 
                       TO_NUMBER(NUM_SEQUENCIAL) 
                   ), 
                   0 
               ) + 1 
          INTO V_PROXIMO 
          FROM FD_UNIDADE_POLICIAL 
         WHERE ID_UNIDADE_PAI IS NULL 
           AND REGEXP_LIKE( 
                   NUM_SEQUENCIAL, 
                   '^[0-9]+$' 
               ); 
 
        :NEW.NUM_SEQUENCIAL := 
            LPAD(V_PROXIMO, 3, '0'); 
 
    ELSE 
 
        /* ===================================================== 
           LOCALIZA O NUM_SEQUENCIAL DA UNIDADE PAI 
           ===================================================== */ 
 
        SELECT NUM_SEQUENCIAL 
          INTO V_SEQ_PAI 
          FROM FD_UNIDADE_POLICIAL 
         WHERE ID_UNIDADE = :NEW.ID_UNIDADE_PAI; 
 
 
        /* ===================================================== 
           LOCALIZA O MAIOR SUFIXO DOS FILHOS DO MESMO PAI 
 
           Exemplo: 
           Pai:     001.001 
           Filhos: 
                    001.001.001 
                    001.001.002 
                    001.001.003 
 
           PrÃ³ximo: 004 
           ===================================================== */ 
 
        SELECT NVL( 
                   MAX( 
                       TO_NUMBER( 
                           REGEXP_SUBSTR( 
                               NUM_SEQUENCIAL, 
                               '[^.]+$' 
                           ) 
                       ) 
                   ), 
                   0 
               ) + 1 
          INTO V_PROXIMO 
          FROM FD_UNIDADE_POLICIAL 
         WHERE ID_UNIDADE_PAI = :NEW.ID_UNIDADE_PAI 
           AND REGEXP_LIKE( 
                   NUM_SEQUENCIAL, 
                   '^[0-9]+(\.[0-9]+)*$' 
               ); 
 
 
        /* ===================================================== 
           MONTA O NOVO NUM_SEQUENCIAL 
           ===================================================== */ 
 
        :NEW.NUM_SEQUENCIAL := 
              V_SEQ_PAI 
           || '.' 
           || LPAD(V_PROXIMO, 3, '0'); 
 
    END IF; 
 
EXCEPTION 
 
    WHEN NO_DATA_FOUND THEN 
        RAISE_APPLICATION_ERROR( 
            -20001, 
            'A unidade pai informada nÃ£o foi encontrada.' 
        ); 
 
END; 

